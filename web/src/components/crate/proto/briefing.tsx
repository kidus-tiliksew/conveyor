// PROTOTYPE. The generated briefing: one headline, a short account of where
// the delivery stands, and the tasks to look at first. It follows the
// requirement insight headline's contract: generated, informative, never
// authority, stamped with its model and time, and regenerated on request.
//
// The prototype's dev server generates it (vite.proto.config.ts). The shipped
// feature would store one briefing per crate on the server and mark it out of
// date when the crate's inputs change.
import { useQuery, useQueryClient } from '@tanstack/react-query'
import { RefreshCw } from 'lucide-react'
import { useMemo } from 'react'
import type { CrateDetail } from '../../../lib/types'
import { cn } from '../../../lib/utils'
import { daysUntil } from '../crate-parts'
import { Button } from '../../ui/button'
import { Skeleton } from '../../ui/skeleton'
import { type CrateInsight, phaseMeta, shortTitle } from './model'

interface Briefing {
  headline: string
  body: string
  watch: Array<{ task_id: string; tone: 'attention' | 'info' | 'positive'; text: string }>
  model: string
  generated_at: string
  fingerprint: string
}

const day = (time: number | undefined) => (time === undefined ? null : new Date(time).toISOString().slice(0, 10))

// What the model reads. Dates stay whole days, so the same crate state asks
// for the same briefing all day.
function briefingFacts(crate: CrateDetail, insight: CrateInsight) {
  return {
    crate: {
      name: crate.name,
      state: crate.state,
      shipped: crate.shipped,
      target_date: crate.target_date,
      days_to_target: crate.target_date ? daysUntil(crate.target_date) : null,
      today: day(insight.now),
    },
    counts: {
      total: crate.total_task_count,
      merged: crate.merged_task_count,
      open: crate.open_task_count,
    },
    delivery: {
      merged_per_week: Number(insight.progress.throughput_per_week.toFixed(1)),
      forecast_finish_day: insight.progress.forecast?.day.slice(0, 10) ?? null,
      median_days_from_created_to_merged:
        insight.progress.median_cycle_seconds === null
          ? null
          : Number((insight.progress.median_cycle_seconds / 86_400).toFixed(1)),
      first_review_round_approval_rate:
        insight.firstPassRate === null ? null : Number(insight.firstPassRate.toFixed(2)),
    },
    where_the_work_is: insight.whereabouts.map((group) => ({ place: group.label, tasks: group.tracks.length })),
    releases: insight.promotions.map((promotion) => ({
      day: day(promotion.at),
      from: promotion.from,
      into: promotion.to,
    })),
    uncovered_declared_requirements: crate.requirements
      .filter((item) => item.task_count === 0)
      .map((item) => item.title),
    tasks: insight.tracks.map((track) => ({
      id: track.id,
      title: track.title,
      doing: phaseMeta[track.phase].label,
      next_action: track.task.next_action.label,
      waiting_on: track.task.next_action.actor,
      base_branch: track.baseBranch,
      created: day(track.createdAt),
      merged: day(track.mergedAt),
      now_in_branches: track.landedOn,
      pull_request: track.task.pull_request?.number ?? null,
      review_rounds: track.reviews.length,
      changes_requested: track.reviews.filter((review) => review.verdict === 'changes_requested').length,
    })),
  }
}

async function requestBriefing(facts: unknown, force: boolean): Promise<Briefing> {
  const response = await fetch('/__proto/crate-summary', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ facts, force }),
  })
  const text = await response.text()
  let body: unknown
  try {
    body = JSON.parse(text)
  } catch {
    throw new Error('The briefing is generated by the prototype dev server, which is not running here.')
  }
  if (!response.ok) throw new Error((body as { error?: string }).error ?? response.statusText)
  return body as Briefing
}

const toneDot: Record<string, string> = {
  attention: 'bg-attention-dot',
  info: 'bg-info',
  positive: 'bg-positive',
}

export function CrateBriefing({
  crate,
  insight,
  canAct,
  hoveredId,
  onHover,
  onSelect,
}: {
  crate: CrateDetail
  insight: CrateInsight | undefined
  canAct: boolean
  hoveredId: string | null
  onHover: (id: string | null) => void
  onSelect: (id: string) => void
}) {
  const queryClient = useQueryClient()
  const facts = useMemo(() => (insight ? briefingFacts(crate, insight) : undefined), [crate, insight])
  const key = useMemo(() => ['proto-crate-briefing', crate.id, JSON.stringify(facts ?? null)], [crate.id, facts])
  const briefing = useQuery({
    queryKey: key,
    queryFn: () => requestBriefing(facts, false),
    enabled: Boolean(facts) && crate.tasks.length > 0,
    staleTime: Number.POSITIVE_INFINITY,
    gcTime: Number.POSITIVE_INFINITY,
    retry: false,
  })
  const regenerate = async () => {
    await queryClient.fetchQuery({ queryKey: key, queryFn: () => requestBriefing(facts, true), staleTime: 0 })
  }

  if (crate.tasks.length === 0) return null
  const data = briefing.data
  const busy = briefing.isFetching
  const words = data ? data.headline.split(' ') : []

  return (
    <section aria-label="Generated briefing" className="px-5 py-4 sm:px-6">
      {!data && !briefing.error && (
        <div className="space-y-2" role="status" aria-label="Writing the briefing">
          <p className="text-xs text-faint">
            Reading {crate.tasks.length} {crate.tasks.length === 1 ? 'task' : 'tasks'} and their activity…
          </p>
          <Skeleton className="h-5 w-3/5" />
          <Skeleton className="h-3.5 w-full" />
          <Skeleton className="h-3.5 w-4/5" />
        </div>
      )}

      {briefing.error != null && !data && (
        <p role="alert" className="rounded-md bg-raised px-3 py-2 text-xs leading-5 text-muted">
          No briefing: {briefing.error instanceof Error ? briefing.error.message : String(briefing.error)}
        </p>
      )}

      {data && (
        <div className={cn('grid gap-x-8 gap-y-3 lg:grid-cols-[minmax(0,1fr)_minmax(0,22rem)]', busy && 'opacity-60')}>
          <div className="min-w-0">
            {/* Plain text: generated words are never rendered as markup. */}
            <p key={data.generated_at} className="text-lg font-semibold leading-snug tracking-tight text-foreground">
              {words.map((word, index) => (
                <span
                  // biome-ignore lint/suspicious/noArrayIndexKey: the words never reorder
                  key={index}
                  className="proto-word inline-block"
                  style={{ animationDelay: `${index * 45}ms` }}
                >
                  {word}
                  {index < words.length - 1 ? ' ' : ''}
                </span>
              ))}
            </p>
            <p className="mt-1.5 max-w-[68ch] text-sm leading-relaxed text-markdown">{data.body}</p>
          </div>
          {(data.watch.length > 0 || canAct) && (
            <div className="min-w-0">
              {/* The heading and the regenerate control share one row, level
                  with the headline. */}
              <div className="mb-1 flex min-h-6 items-center justify-between gap-2">
                {data.watch.length > 0 && (
                  <h3 className="text-[11px] font-medium uppercase tracking-wide text-faint">Look at first</h3>
                )}
                {canAct && (
                  <Button
                    size="sm"
                    variant="outline"
                    className="ml-auto h-6 shrink-0 px-2 text-[11px] [&_svg]:size-3"
                    disabled={busy}
                    onClick={() => void regenerate()}
                  >
                    <RefreshCw className={cn(busy && 'animate-spin')} />
                    Regenerate
                  </Button>
                )}
              </div>
              <ul className="-mx-2">
                {data.watch.map((item) => {
                  const track = insight?.byId.get(item.task_id)
                  if (!track) return null
                  return (
                    <li key={item.task_id}>
                      <button
                        type="button"
                        onClick={() => onSelect(track.id)}
                        onMouseEnter={() => onHover(track.id)}
                        onMouseLeave={() => onHover(null)}
                        onFocus={() => onHover(track.id)}
                        onBlur={() => onHover(null)}
                        className={cn(
                          'flex w-full items-start gap-2 rounded-md px-2 py-1.5 text-left hover:bg-raised focus-visible:bg-raised focus-visible:outline-none',
                          hoveredId === track.id && 'bg-raised',
                        )}
                      >
                        <span
                          className={cn('mt-[7px] size-1.5 shrink-0 rounded-full', toneDot[item.tone] ?? 'bg-info')}
                        />
                        <span className="min-w-0">
                          <span className="block truncate text-sm font-medium text-foreground">
                            {shortTitle(track.title, 54)}
                          </span>
                          <span className="block text-xs leading-snug text-muted">{item.text}</span>
                        </span>
                      </button>
                    </li>
                  )
                })}
              </ul>
            </div>
          )}
        </div>
      )}
    </section>
  )
}
