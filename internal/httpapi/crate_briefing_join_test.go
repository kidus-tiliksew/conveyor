// crateJoinActor is the actor ID of the maintainer that the editor token
// authenticates.
var crateJoinActor = store.UserActorID(intakeOwner(core.WorkspaceRoleMaintainer))

// blockingBriefingAgent returns a model whose calls wait for release.
func (h *crateBriefingHarness) blockingBriefingAgent(t *testing.T, replies ...insightReply) *insightAgent {
	t.Helper()
	agent := &insightAgent{started: make(chan struct{}, 16), release: make(chan struct{}), replies: replies, reply: insightReply{output: h.reply(t), model: "served-model"}}
	h.install(agent, config.TriageRoute{Model: "triage-model"})
	return agent
}

// waitCrateBriefingJobs waits until every background generation ended.
func waitCrateBriefingJobs(t *testing.T, server *Server) {
	t.Helper()
	done := make(chan struct{})
	go func() {
		server.crateBriefingJobs.Wait()
		close(done)
	}()
	select {
	case <-done:
	case <-time.After(10 * time.Second):
		t.Fatal("a background briefing generation did not end")
	}
}

func waitModelStarted(t *testing.T, agent *insightAgent) {
	t.Helper()
	select {
	case <-agent.started:
	case <-time.After(10 * time.Second):
		t.Fatal("the background generation did not call the model")
	}
}

// storedBriefingFor returns the crate's stored briefing, or false.
func (h *crateBriefingHarness) storedBriefingFor(t *testing.T, crateID string) (store.CrateBriefing, bool) {
	t.Helper()
	briefing, err := h.store.(crateBackend).GetCrateBriefing(h.ctx, crateID)
	if errors.Is(err, store.ErrNotFound) {
		return store.CrateBriefing{}, false
	}
	if err != nil {
		t.Fatal(err)
	}
	return briefing, true
}

func (h *crateBriefingHarness) requireJoinBriefing(t *testing.T, crateID string) store.CrateBriefing {
	t.Helper()
	stored, ok := h.storedBriefingFor(t, crateID)
	if !ok {
		t.Fatalf("crate %s has no stored briefing", crateID)
	}
	if stored.GeneratedBy != crateJoinActor || stored.Headline != crateBriefingHeadline {
		t.Fatalf("stored %+v, want the reply generated by %s", stored, crateJoinActor)
	}
	return stored
}

func (h *crateBriefingHarness) requireJobsStarted(t *testing.T, want int64) {
	t.Helper()
	if got := h.server.crateBriefingJobsStarted.Load(); got != want {
		t.Fatalf("background generations started=%d, want %d", got, want)
	}
}

// serveAsync serves one request on another goroutine. The result channel
// receives the recorder when the handler returns.
func (h *crateBriefingHarness) serveAsync(request *http.Request) <-chan *httptest.ResponseRecorder {
	done := make(chan *httptest.ResponseRecorder, 1)
	go func() {
		response := httptest.NewRecorder()
		h.handler.ServeHTTP(response, request)
		done <- response
	}()
	return done
}

func captureCrateLog(t *testing.T) (*bytes.Buffer, func()) {
	t.Helper()
	var captured bytes.Buffer
	var mu sync.Mutex
	previous := log.Writer()
	log.SetOutput(writerFunc(func(p []byte) (int, error) {
		mu.Lock()
		defer mu.Unlock()
		return captured.Write(p)
	}))
	restore := func() { log.SetOutput(previous) }
	t.Cleanup(restore)
	return &captured, restore
}

type writerFunc func([]byte) (int, error)

func (f writerFunc) Write(p []byte) (int, error) { return f(p) }

// TestCrateBriefingAfterJoinRESTCreateReturnsBeforeModel: a REST creation
// that names a crate with no briefing answers 201 while the model call it
// started is still waiting, and the generation then stores the briefing
// with the acting member as generated_by. Storing it changes no recorded
// state.
func TestCrateBriefingAfterJoinRESTCreateReturnsBeforeModel(t *testing.T) {
	h := newCrateBriefingHarness(t)
	fresh := h.createCrate(t, h.editor, map[string]any{"name": "Fresh crate"})
	agent := h.blockingBriefingAgent(t)
	body, _ := json.Marshal(map[string]any{"body": "Crate intake.", "repo": "api", "crate_id": fresh.ID})
	request := httptest.NewRequest(http.MethodPost, "/v1/tasks?workspace_id=alpha", bytes.NewReader(body))
	request.Header.Set("Authorization", "Bearer "+h.editor)
	request.Header.Set("Content-Type", "application/json")
	var response *httptest.ResponseRecorder
	select {
	case response = <-h.serveAsync(request):
	case <-time.After(10 * time.Second):
		t.Fatal("the creation response waited for the model")
	}
	if response.Code != http.StatusCreated || !strings.Contains(response.Body.String(), fresh.ID) {
		t.Fatalf("create status=%d body=%s", response.Code, response.Body.String())
	}
	waitModelStarted(t, agent)
	if _, ok := h.storedBriefingFor(t, fresh.ID); ok {
		t.Fatal("a briefing was stored before the model answered")
	}
	before := h.recorded(t)
	close(agent.release)
	waitCrateBriefingJobs(t, h.server)
	h.requireJoinBriefing(t, fresh.ID)
	h.requireJobsStarted(t, 1)
	if calls := agent.callCount(); calls != 1 {
		t.Fatalf("model calls=%d, want 1", calls)
	}
	if after := h.recorded(t); after != before {
		t.Fatalf("storing the briefing recorded state:\nbefore %s\nafter  %s", before, after)
	}
}

// TestCrateBriefingAfterJoinMultipartCreateAndReplay: the multipart intake
// that planning push uses starts one generation. A model failure stores
// nothing, logs the redacted cause, and schedules no retry. A replayed
// keyed create starts nothing, and a new creation in the same crate starts
// one, because the crate still has no briefing.
func TestCrateBriefingAfterJoinMultipartCreateAndReplay(t *testing.T) {
	const secret = "hunter2hunter2hunter2hunter2"
	h := newCrateBriefingHarness(t)
	h.install(h.agent, config.TriageRoute{Model: "triage-model"})
	h.server.WorkOrders.RedactionSecrets = insightSecretSource{secrets: []string{secret}}
	fresh := h.createCrate(t, h.editor, map[string]any{"name": "Planned crate"})
	h.agent.replies = []insightReply{{err: errors.New("provider refused key " + secret)}}
	h.agent.reply = insightReply{output: h.reply(t), model: "served-model"}
	captured, restore := captureCrateLog(t)

	fields := map[string]any{"body": "Planned crate task.", "repo": "api", "crate_id": fresh.ID}
	first := h.postTaskMultipart(t, h.editor, fields, "plan-push-item-1")
	if first.status != http.StatusCreated || first.task.TaskCrateID() != fresh.ID {
		t.Fatalf("multipart status=%d body=%s", first.status, first.body)
	}
	waitCrateBriefingJobs(t, h.server)
	restore()
	if _, ok := h.storedBriefingFor(t, fresh.ID); ok {
		t.Fatal("a failed generation stored a briefing")
	}
	if logged := captured.String(); strings.Contains(logged, secret) || !strings.Contains(logged, "crate briefing generation for "+fresh.ID) {
		t.Fatalf("log %q, want the redacted failure", logged)
	}
	h.requireJobsStarted(t, 1)
	if calls := h.agent.callCount(); calls != 1 {
		t.Fatalf("model calls after a failure=%d, want 1 and no retry", calls)
	}

	replay := h.postTaskMultipart(t, h.editor, fields, "plan-push-item-1")
	if replay.status != http.StatusOK || replay.task.ID != first.task.ID {
		t.Fatalf("replay status=%d body=%s", replay.status, replay.body)
	}
	waitCrateBriefingJobs(t, h.server)
	h.requireJobsStarted(t, 1)

	second := h.postTaskMultipart(t, h.editor, map[string]any{"body": "Second planned task.", "repo": "api", "crate_id": fresh.ID}, "plan-push-item-2")
	if second.status != http.StatusCreated {
		t.Fatalf("second status=%d body=%s", second.status, second.body)
	}
	waitCrateBriefingJobs(t, h.server)
	h.requireJobsStarted(t, 2)
	h.requireJoinBriefing(t, fresh.ID)
	if calls := h.agent.callCount(); calls != 2 {
		t.Fatalf("model calls=%d, want 2", calls)
	}
}

// TestMCPCreateTaskCrateStartsBriefing: MCP create_task in a crate with no
// briefing starts one generation through the shared intake, and an equal
// retry of the same idempotency key starts none.
func TestMCPCreateTaskCrateStartsBriefing(t *testing.T) {
	h := newCrateBriefingHarness(t)
	h.install(h.agent, config.TriageRoute{Model: "triage-model"})
	h.agent.reply = insightReply{output: h.reply(t), model: "served-model"}
	fresh := h.createCrate(t, h.editor, map[string]any{"name": "Agent crate"})
	args := map[string]any{"workspace_id": "alpha", "body": "Agent crate task.", "repo": "api", "crate_id": fresh.ID, "idempotency_key": "mcp-briefing-1"}
	created := h.callMCP(t, h.editor, "create_task", args)
	if created.errText != "" || !created.created || created.task.TaskCrateID() != fresh.ID {
		t.Fatalf("create_task = %+v", created)
	}
	waitCrateBriefingJobs(t, h.server)
	h.requireJobsStarted(t, 1)
	h.requireJoinBriefing(t, fresh.ID)
	again := h.callMCP(t, h.editor, "create_task", args)
	if again.errText != "" || again.created || again.task.ID != created.task.ID {
		t.Fatalf("equal retry = %+v", again)
	}
	waitCrateBriefingJobs(t, h.server)
	h.requireJobsStarted(t, 1)
	if calls := h.agent.callCount(); calls != 1 {
		t.Fatalf("model calls=%d, want 1", calls)
	}
}

// TestCrateBriefingAfterMembershipChange: PUT /v1/tasks/{id}/crate starts
// one generation only when its write changed the task's crate. A same-crate
// repeat, a removal, and a refused join of a closed crate start none. A join
// of a crate with a stored briefing starts none and calls no model, even when
// that briefing is out of date.
func TestCrateBriefingAfterMembershipChange(t *testing.T) {
	h := newCrateBriefingHarness(t)
	h.install(h.agent, config.TriageRoute{Model: "triage-model"})
	h.agent.replies = []insightReply{{err: errors.New("provider unavailable")}}
	h.agent.reply = insightReply{output: h.reply(t), model: "served-model"}
	first := h.createCrate(t, h.editor, map[string]any{"name": "First"})
	second := h.createCrate(t, h.editor, map[string]any{"name": "Second"})
	shut := h.createCrate(t, h.editor, map[string]any{"name": "Shut"})
	if status, raw := h.do(t, h.editor, http.MethodPatch, "/v1/crates/"+shut.ID, `{"state":"closed"}`); status != http.StatusOK {
		t.Fatalf("close status=%d body=%s", status, raw)
	}
	if _, err := h.store.(crateBackend).RecordCrateBriefing(h.ctx, store.CrateBriefing{CrateID: h.crate.ID, Fingerprint: "fp-out-of-date", Headline: "Stored headline.", Account: "Stored.", Model: "m", GeneratedBy: "user:someone"}); err != nil {
		t.Fatal(err)
	}
	task := h.task(t, "")
	put := func(crateID string, want int) {
		t.Helper()
		status, raw := h.do(t, h.editor, http.MethodPut, "/v1/tasks/"+task.ID+"/crate", map[string]any{"crate_id": crateID})
		if status != want {
			t.Fatalf("join %s status=%d body=%s, want %d", crateID, status, raw, want)
		}
		waitCrateBriefingJobs(t, h.server)
	}

	put(first.ID, http.StatusOK)
	h.requireJobsStarted(t, 1)
	if _, ok := h.storedBriefingFor(t, first.ID); ok || h.agent.callCount() != 1 {
		t.Fatalf("a failed first generation stored=%t calls=%d", ok, h.agent.callCount())
	}
	put(first.ID, http.StatusOK)
	h.requireJobsStarted(t, 1)
	if status, raw := h.do(t, h.editor, http.MethodDelete, "/v1/tasks/"+task.ID+"/crate", nil); status != http.StatusOK {
		t.Fatalf("leave status=%d body=%s", status, raw)
	}
	waitCrateBriefingJobs(t, h.server)
	h.requireJobsStarted(t, 1)
	put(shut.ID, http.StatusConflict)
	h.requireJobsStarted(t, 1)

	put(h.crate.ID, http.StatusOK)
	h.requireJobsStarted(t, 1)
	if calls := h.agent.callCount(); calls != 1 {
		t.Fatalf("joining a crate with a stored briefing called the model: calls=%d", calls)
	}
	if stored, _ := h.storedBriefingFor(t, h.crate.ID); stored.Headline != "Stored headline." {
		t.Fatalf("the stored briefing changed: %+v", stored)
	}

	put(second.ID, http.StatusOK)
	h.requireJobsStarted(t, 2)
	h.requireJoinBriefing(t, second.ID)
	if calls := h.agent.callCount(); calls != 2 {
		t.Fatalf("model calls=%d, want 2", calls)
	}
	if _, ok := h.storedBriefingFor(t, first.ID); ok {
		t.Fatal("a crate the task left gained a briefing")
	}
}

