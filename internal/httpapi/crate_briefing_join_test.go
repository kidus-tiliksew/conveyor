// crateJoinContext is the context a request of the token's owner carries:
// workspace, credential, and actor.
func crateJoinContext(parent context.Context, role core.WorkspaceRole) context.Context {
	credential := core.AuthenticatedCredential{ID: "pat_" + string(role), OwnerUserID: intakeOwner(role), Kind: core.CredentialUser, Scope: core.CredentialScopeUser}
	ctx := store.WithCredential(store.WithWorkspace(parent, "alpha"), credential)
	return store.WithActor(ctx, store.Actor{ID: store.UserActorID(credential.OwnerUserID), Role: core.ActorUser})
}

