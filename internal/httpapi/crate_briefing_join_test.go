// TestCrateBriefingAfterJoinSerializesWithOtherGenerations: two starts for
// one crate and a POST share the workspace and crate mutex. The first stores
// the briefing, the second start finds it and calls no model, and the POST
// that waited answers 409 crate_briefing_current. A POST that holds the mutex
// first makes a later start skip.
func TestCrateBriefingAfterJoinSerializesWithOtherGenerations(t *testing.T) {
	h := newCrateBriefingHarness(t)
	fresh := h.createCrate(t, h.editor, map[string]any{"name": "Contended"})
	h.task(t, fresh.ID)
	agent := h.blockingBriefingAgent(t)
	key := requirementInsightKey{workspace: "alpha", requirement: fresh.ID}
	editor := crateJoinContext(t.Context(), core.WorkspaceRoleMaintainer)

	h.server.startCrateBriefingAfterJoin(editor, fresh.ID)
	waitModelStarted(t, agent)
	h.server.startCrateBriefingAfterJoin(editor, fresh.ID)
	waitForCrateBriefingWaiters(t, h.server, key, 2)
	post := h.postAsync(h.editor, fresh.ID)
	waitForCrateBriefingWaiters(t, h.server, key, 3)
	close(agent.release)
	waitCrateBriefingJobs(t, h.server)
	if result := <-post; result.code != http.StatusConflict || !strings.Contains(result.body, `"error":"crate_briefing_current"`) {
		t.Fatalf("waiting POST status=%d body=%s", result.code, result.body)
	}
	if calls := agent.callCount(); calls != 1 {
		t.Fatalf("model calls=%d, want 1", calls)
	}
	h.requireJoinBriefing(t, fresh.ID)

	other := h.createCrate(t, h.editor, map[string]any{"name": "Posted first"})
	h.task(t, other.ID)
	agent = h.blockingBriefingAgent(t)
	otherKey := requirementInsightKey{workspace: "alpha", requirement: other.ID}
	posted := h.postAsync(h.editor, other.ID)
	waitModelStarted(t, agent)
	h.server.startCrateBriefingAfterJoin(editor, other.ID)
	waitForCrateBriefingWaiters(t, h.server, otherKey, 2)
	close(agent.release)
	if result := <-posted; result.code != http.StatusOK {
		t.Fatalf("POST status=%d body=%s", result.code, result.body)
	}
	waitCrateBriefingJobs(t, h.server)
	if calls := agent.callCount(); calls != 1 {
		t.Fatalf("model calls after a POST won=%d, want 1", calls)
	}
}

