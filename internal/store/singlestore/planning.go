func (s *Store) ListPendingProposals(ctx context.Context) ([]core.PendingProposal, error) {
	rows, err := documentRows(ctx, s.db, `
		SELECT proposal_id,title,tier,version,origin_type,origin_id,target_kind,justification,proposed_at
		FROM (
			SELECT v.document_id AS proposal_id,d.title,'system_design' AS tier,v.version,
				CASE WHEN v.origin_task_id IS NOT NULL THEN 'task' WHEN v.origin_session_id IS NOT NULL THEN 'session' ELSE 'operator' END AS origin_type,
				coalesce(v.origin_task_id,v.origin_session_id,'') AS origin_id,'' AS target_kind,'' AS justification,v.created_at AS proposed_at
			FROM system_design_versions v
			JOIN system_designs d ON d.workspace_id=v.workspace_id AND d.id=v.document_id
			WHERE v.workspace_id=? AND d.archived_at IS NULL AND NOT v.confirmed AND NOT v.dismissed
			UNION ALL
			SELECT v.requirement_id,r.title,'requirement' AS tier,v.version,
				CASE WHEN v.origin_task_id <> '' THEN 'task' WHEN v.origin_session_id <> '' THEN 'session' WHEN v.origin_drift_id <> '' THEN 'drift' ELSE v.origin END AS origin_type,
				coalesce(nullif(v.origin_task_id,''),nullif(v.origin_session_id,''),nullif(v.origin_drift_id,''),'') AS origin_id,'' AS target_kind,'' AS justification,v.created_at AS proposed_at
			FROM requirement_versions v
			JOIN requirements r ON r.workspace_id=v.workspace_id AND r.id=v.requirement_id
			WHERE v.workspace_id=? AND r.archived_at IS NULL AND NOT v.confirmed AND NOT v.retired
			  AND v.version > coalesce(r.current_version,0)
			UNION ALL
			SELECT d.id,d.statement,'decision' AS tier,NULL AS version,
				CASE WHEN d.origin_task_id IS NOT NULL THEN 'task' WHEN d.origin_session_id IS NOT NULL THEN 'session' ELSE 'operator' END AS origin_type,
				coalesce(d.origin_task_id,d.origin_session_id,'') AS origin_id,'' AS target_kind,'' AS justification,d.created_at AS proposed_at
			FROM decisions d
			WHERE d.workspace_id=? AND d.status='proposed'
			UNION ALL
			SELECT p.target_id,p.target_title,'task_context',NULL,'task',p.task_id,p.target_kind,p.justification,p.created_at
			FROM task_context_proposals p
			JOIN tasks t ON t.workspace_id=p.workspace_id AND t.id=p.task_id
			WHERE p.workspace_id=? AND p.state='proposed' AND t.state NOT IN ('merged','closed')
		) pending
		ORDER BY proposed_at,tier,proposal_id,version`, documentWorkspace(ctx), documentWorkspace(ctx), documentWorkspace(ctx), documentWorkspace(ctx))
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := make([]core.PendingProposal, 0)
	for rows.Next() {
		var item core.PendingProposal
		var version *int
		if err = rows.Scan(&item.ID, &item.Title, &item.Tier, &version, &item.OriginType, &item.OriginID, &item.TargetKind, &item.Justification, &item.ProposedAt); err != nil {
			return nil, err
		}
		if version != nil {
			item.Version = *version
		}
		out = append(out, item)
	}
	return out, rows.Err()
}

func (s *Store) PendingProposalsProjection(ctx context.Context) (store.PendingProposalsProjection, error) {
	items, err := s.ListPendingProposals(ctx)
	result := store.PendingProposalsProjection{Items: items}
	if err != nil {
		return result, err
	}
	rows, err := documentRows(ctx, s.db, `SELECT t.id,t.state FROM tasks t WHERE t.workspace_id=? AND NOT EXISTS(SELECT 1 FROM tasks c WHERE c.workspace_id=t.workspace_id AND c.parent_task_id=t.id)`, documentWorkspace(ctx))
	if err != nil {
		return result, err
	}
	states := map[string]core.TaskState{}
	for rows.Next() {
		var id string
		var state core.TaskState
		if err = rows.Scan(&id, &state); err != nil {
			rows.Close()
			return result, err
		}
		states[id] = state
	}
	err = rows.Err()
	rows.Close()
	if err != nil || len(states) == 0 {
		return result, err
	}
	markers, err := s.ListActivityMarkers(ctx)
	if err != nil {
		return result, err
	}
	pendingContext, origins, authority := map[string]bool{}, map[string]bool{}, map[string]bool{}
	for _, p := range items {
		if p.OriginType == "task" {
			origins[p.OriginID] = true
			if p.Tier == "task_context" {
				pendingContext[p.OriginID] = true
			}
		}
	}
	rows, err = documentRows(ctx, s.db, `SELECT DISTINCT task_id FROM work_orders WHERE workspace_id=? AND ((stage='implement' AND state='submitted') OR (stage='review' AND state IN ('queued','claimed','submitted')))`, documentWorkspace(ctx))
	if err != nil {
		return result, err
	}
	for rows.Next() {
		var id string
		if err = rows.Scan(&id); err != nil {
			rows.Close()
			return result, err
		}
		authority[id] = origins[id]
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return result, err
	}
	byID := map[string]store.ActivityMarker{}
	for _, m := range markers {
		byID[m.TaskID] = m
	}
	for id, state := range states {
		m := byID[id]
		if core.TaskTerminal(state) {
			m.Stalled = nil
		}
		if store.TaskNeedsAttention(core.Task{ID: id, State: state}, m, authority[id], pendingContext[id]) {
			result.TaskCount++
		}
	}
	return result, nil
}

// Acquisition is bounded independently of the callback lifetime. SingleStore
// can keep waiting on an INSERT/row lock despite a session lock_wait_timeout;
// canceling the acquisition query discards that connection and its transaction.
func (s *Store) WithPlanningSessionRun(ctx context.Context, id string, fn func(context.Context) error) error {
	ws, err := workspace(ctx)
	if err != nil {
		return err
	}
	acquireCtx, cancel := context.WithTimeout(ctx, time.Second)
	defer cancel()
	conn, err := s.db.Conn(acquireCtx)
	if err != nil {
		return planningRunAcquireError(ctx, acquireCtx, err)
	}
	defer conn.Close()
	// The parent context owns the transaction. Finishing acquisition must not
	// cancel a successfully claimed run while its callback is still working.
	tx, err := conn.BeginTx(ctx, nil)
	if err != nil {
		return translateBackendConflict(err)
	}
	defer tx.Rollback()
	if err = lockKey(acquireCtx, tx, fmt.Sprintf("planning-run:%d:%s:%s", len(ws), ws, id)); err != nil {
		return planningRunAcquireError(ctx, acquireCtx, err)
	}
	cancel()
	return fn(ctx)
}
func planningRunAcquireError(ctx, acquireCtx context.Context, err error) error {
	if ctx.Err() != nil {
		return ctx.Err()
	}
	var driverErr *mysql.MySQLError
	if acquireCtx.Err() != nil || errors.As(err, &driverErr) && driverErr.Number == 1205 {
		return store.ErrPlanningSessionRunConflict
	}
	return translateBackendConflict(err)
}

func documentParent(ctx context.Context, tx *sql.Tx, table, id string) error {
	if id == "" {
		return nil
	}
	switch table {
	case "requirements", "system_designs", "planning_sessions", "tasks", "artifacts", "planning_bundles":
	default:
		return fmt.Errorf("unsupported document parent")
	}
	var exists int
	err := documentRow(ctx, tx, "SELECT 1 FROM "+table+" WHERE workspace_id=? AND id=? FOR UPDATE", documentWorkspace(ctx), id).Scan(&exists)
	return notFound(err, "%s %s", table, id)
}

