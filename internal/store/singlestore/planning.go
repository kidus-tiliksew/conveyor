func activatePendingTaskContextTx(ctx context.Context, tx *sql.Tx, workspaceID, documentID string, version int, design bool) error {
	addedKind, removedKind, activeKind := store.TaskContextRequirementAdded, store.TaskContextRequirementRemoved, store.TaskContextRequirementActive
	if design {
		addedKind, removedKind, activeKind = store.TaskContextDesignAdded, store.TaskContextDesignRemoved, store.TaskContextDesignActive
	}
	rows, err := documentRows(ctx, tx, `SELECT task_id,kind,payload_json FROM events
		WHERE workspace_id=? AND task_id IS NOT NULL AND kind IN (?,?)
		  AND JSON_EXTRACT_STRING(payload_json,'id')=? ORDER BY task_id,id`, workspaceID, addedKind, removedKind, documentID)
	if err != nil {
		return err
	}
	byTask := map[string][]core.Event{}
	for rows.Next() {
		var taskID, kind string
		var payload json.RawMessage
		if err = rows.Scan(&taskID, &kind, &payload); err != nil {
			rows.Close()
			return err
		}
		byTask[taskID] = append(byTask[taskID], core.Event{TaskID: taskID, Kind: kind, Payload: payload})
	}
	if err = rows.Err(); err != nil {
		rows.Close()
		return err
	}
	rows.Close()
	for taskID, events := range byTask {
		if !store.PendingTaskContextAttachment(events, documentID, version, design) {
			continue
		}
		if err = insertEvent(ctx, tx, core.Event{TaskID: taskID, Kind: activeKind,
			Payload: core.JSONPayload(map[string]any{"id": documentID, "version": version})}); err != nil {
			return err
		}
	}
	return nil
}

func validateTaskContextTx(ctx context.Context, tx *sql.Tx, workspaceID string, input store.TaskContextInput) (map[string]int, error) {
	for _, id := range input.RequirementIDs {
		var current sql.NullInt32
		var archivedAt *time.Time
		err := documentRow(ctx, tx, `SELECT current_version,archived_at FROM requirements WHERE workspace_id=? AND id=?`, workspaceID, id).Scan(&current, &archivedAt)
		if errors.Is(err, sql.ErrNoRows) {
			return nil, &store.TaskContextReferenceError{Kind: "requirement", ID: id, Reason: "was not found in this workspace"}
		}
		if err != nil {
			return nil, err
		}
		if !current.Valid || current.Int32 <= 0 {
			return nil, &store.TaskContextReferenceError{Kind: "requirement", ID: id, Reason: "has no confirmed version"}
		}
		if archivedAt != nil {
			return nil, &store.RequirementArchivedError{RequirementID: id}
		}
	}
	versions := map[string]int{}
	for _, id := range input.DesignIDs {
		var current sql.NullInt32
		var archivedAt *time.Time
		err := documentRow(ctx, tx, `SELECT current_version,archived_at FROM system_designs WHERE workspace_id=? AND id=?`, workspaceID, id).Scan(&current, &archivedAt)
		if errors.Is(err, sql.ErrNoRows) {
			return nil, &store.TaskContextReferenceError{Kind: "system design", ID: id, Reason: "was not found in this workspace"}
		}
		if err != nil {
			return nil, err
		}
		if !current.Valid || current.Int32 <= 0 {
			return nil, &store.TaskContextReferenceError{Kind: "system design", ID: id, Reason: "has no confirmed version"}
		}
		if archivedAt != nil {
			return nil, &store.SystemDesignArchivedError{DocumentID: id}
		}
		versions[id] = int(current.Int32)
	}
	return versions, nil
}
